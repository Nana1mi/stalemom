"""Generate reports/e5_d1.md and reports/e5_d2.md directly from CSV files.

Rule §2.2: Every number in the reports must correspond to a row in a CSV file,
and tables must be generated by script from CSVs.
Rule §2.8: Mechanisms without direct causal experiment proof must be labeled as
hypotheses ('假设'), never '证明' or '确证'.
"""

import csv
from collections import defaultdict
from pathlib import Path


def load_csv(path: Path) -> list[dict]:
    with open(path, "r", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def fmt(val, digits: int = 4) -> str:
    v = float(val)
    if v != v:
        return "NaN"
    if v == float("inf"):
        return "inf"
    if v == float("-inf"):
        return "-inf"
    return f"{v:.{digits}f}"


def fmt_pm(mean_val, se_val, digits: int = 4) -> str:
    m = float(mean_val)
    s = float(se_val)
    if m != m:
        return "NaN"
    if m == float("inf"):
        return "inf"
    return f"{m:.{digits}f} ± {s:.{digits}f}"


